/**
 * Calculates profile completion percentage and verification badge tier
 * Criteria:
 * - New Seller (gray): Incomplete profile
 * - Verified Seller (blue checkmark): photo, name, phone, and location filled
 * - Trusted Seller (gold star): ALL fields including business name and description complete
 */
export function calculateSellerBadge(seller) {
  if (!seller) return { badge: "new", percentage: 0, checklist: [] };

  const hasPhoto = Boolean(seller.photo && seller.photo.trim() !== "");
  const hasName = Boolean(seller.name && seller.name.trim() !== "");
  const hasPhone = Boolean(seller.phone && seller.phone.trim() !== "");
  const hasLocation = Boolean(seller.location && seller.location.trim() !== "");
  const hasBusinessName = Boolean(seller.businessName && seller.businessName.trim() !== "");
  const hasBusinessDesc = Boolean(seller.businessDesc && seller.businessDesc.trim() !== "");

  const checklist = [
    { label: "Profile Photo Uploaded", completed: hasPhoto, weight: 20 },
    { label: "Full Display Name", completed: hasName, weight: 20 },
    { label: "Verified Phone Number", completed: hasPhone, weight: 20 },
    { label: "City & Service Area", completed: hasLocation, weight: 15 },
    { label: "Registered Business Name", completed: hasBusinessName, weight: 15 },
    { label: "Detailed Business Description", completed: hasBusinessDesc, weight: 10 },
  ];

  let percentage = 0;
  checklist.forEach(item => {
    if (item.completed) percentage += item.weight;
  });

  let badge = "new";
  if (hasPhoto && hasName && hasPhone && hasLocation && hasBusinessName && hasBusinessDesc) {
    badge = "trusted"; // Trusted Seller (gold star)
  } else if (hasPhoto && hasName && hasPhone && hasLocation) {
    badge = "verified"; // Verified Seller (blue checkmark)
  } else {
    badge = "new"; // New Seller (gray)
  }

  return { badge, percentage, checklist };
}
